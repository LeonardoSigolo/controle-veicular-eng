create table if not exists veiculo (
    id             bigint generated by default as identity primary key,
    marca          varchar(255) not null,
    modelo         varchar(255) not null,
    ano            integer      not null,
    placa          varchar(255) not null unique,
    cor            varchar(255) not null,
    quilometragem  integer      not null,
    combustivel    varchar(255) not null
);

create table if not exists manutencao (
    id              bigint generated by default as identity primary key,
    veiculo_id      bigint       not null,
    tipo            varchar(255) not null,
    descricao       varchar(255),
    data            date         not null,
    quilometragem   integer      not null,
    custo           numeric(38,2) not null,
    oficina         varchar(255),
    proxima_revisao date
);

create table if not exists documento (
    id               bigint generated by default as identity primary key,
    veiculo_id       bigint       not null,
    tipo             varchar(255) not null,
    numero           varchar(255) not null,
    data_emissao     date,
    data_vencimento  date,
    observacao       varchar(255)
);

-- Segurança: o Supabase expõe o schema "public" por uma API REST própria.
-- Ativando o RLS (sem nenhuma policy), essa API pública não consegue ler nem
-- gravar nestas tabelas. A aplicação Spring Boot continua funcionando porque
-- conecta pelo JDBC com o usuário "postgres", que ignora o RLS.
alter table veiculo     enable row level security;
alter table manutencao  enable row level security;
alter table documento   enable row level security;
